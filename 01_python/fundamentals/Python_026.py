"""
بخش اول: یافتن بزرگترین عدد
Part 1: Finding the Maximum Number
"""
def find_maximum():
    """
    شرح کامل:
    این برنامه پنج عدد از کاربر دریافت می‌کند و بزرگترین آنها را پیدا می‌کند.
    
    روش کار:
    1. اولین عدد را به عنوان بزرگترین عدد در نظر می‌گیریم
    2. هر عدد جدید را با بزرگترین عدد فعلی مقایسه می‌کنیم
    3. اگر عدد جدید بزرگتر بود، آن را جایگزین می‌کنیم
    
    نکات کلیدی:
    - از float استفاده می‌کنیم تا اعداد اعشاری هم قبول شوند
    - از f-string برای نمایش خروجی استفاده می‌کنیم
    - مقایسه‌ها به صورت متوالی انجام می‌شوند
    
    مثال:
    ورودی: 5.2, 3.8, 9.1, 2.4, 7.5
    خروجی: 9.1
    """
    maxnum = float(input("عدد اول را وارد کنید: "))    # اولین عدد را می‌گیریم
    num2 = float(input("عدد دوم را وارد کنید: "))     # عدد دوم
    num3 = float(input("عدد سوم را وارد کنید: "))     # عدد سوم
    num4 = float(input("عدد چهارم را وارد کنید: "))   # عدد چهارم
    num5 = float(input("عدد پنجم را وارد کنید: "))    # عدد پنجم

    # مقایسه متوالی اعداد
    if num2 > maxnum:
        maxnum = num2    # اگر عدد دوم بزرگتر بود، جایگزین می‌شود
    if num3 > maxnum:
        maxnum = num3    # اگر عدد سوم بزرگتر بود، جایگزین می‌شود
    if num4 > maxnum:
        maxnum = num4    # اگر عدد چهارم بزرگتر بود، جایگزین می‌شود
    if num5 > maxnum:
        maxnum = num5    # اگر عدد پنجم بزرگتر بود، جایگزین می‌شود

    print(f"بزرگترین عدد: {maxnum}")

"""
بخش دوم: چاپ مثلث ساده
Part 2: Simple Triangle Pattern
"""
def print_simple_triangle():
    """
    شرح کامل:
    این برنامه یک مثلث ساده با ستاره چاپ می‌کند که در هر سطر تعداد ستاره‌ها افزایش می‌یابد.
    
    روش کار:
    1. از یک حلقه برای تکرار سطرها استفاده می‌کنیم
    2. در هر سطر به تعداد شماره سطر، ستاره چاپ می‌کنیم
    
    نکات کلیدی:
    - از عملگر * برای تکرار رشته استفاده می‌کنیم
    - range(5) اعداد 0 تا 4 را تولید می‌کند
    
    خروجی:
    *
    **
    ***
    ****
    """
    for i in range(5):           # 5 سطر خواهیم داشت
        print("*" * i)           # در هر سطر i تا ستاره چاپ می‌شود

"""
بخش سوم: چاپ مستطیل
Part 3: Rectangle Pattern
"""
def print_rectangle():
    """
    شرح کامل:
    این برنامه یک مستطیل با عرض ثابت چاپ می‌کند.
    
    روش کار:
    1. از یک حلقه برای تکرار سطرها استفاده می‌کنیم
    2. در هر سطر تعداد ثابتی ستاره چاپ می‌کنیم
    
    نکات کلیدی:
    - عرض مستطیل ثابت است (در اینجا 4)
    - ارتفاع مستطیل با تعداد تکرار حلقه تعیین می‌شود
    
    خروجی:
    ****
    ****
    ****
    """
    for i in range(3):           # 3 سطر خواهیم داشت
        print("*" * 4)           # در هر سطر 4 ستاره چاپ می‌شود

"""
بخش چهارم: مستطیل با جابجایی
Part 4: Shifted Rectangle Pattern
"""
def print_shifted_rectangle():
    """
    شرح کامل:
    این برنامه یک مستطیل را با فاصله‌های متغیر از سمت چپ چاپ می‌کند.
    
    روش کار:
    1. از یک حلقه برای تکرار سطرها استفاده می‌کنیم
    2. در هر سطر ابتدا فاصله خالی و سپس ستاره‌ها را چاپ می‌کنیم
    
    نکات کلیدی:
    - از عملگر + برای ترکیب رشته‌ها استفاده می‌کنیم
    - تعداد فاصله‌های خالی در هر سطر افزایش می‌یابد
    
    خروجی:
    ****
     ****
      ****
       ****
    """
    for i in range(4):                # 4 سطر خواهیم داشت
        print(" " * i + "*" * 4)      # اول فاصله، بعد ستاره

"""
بخش پنجم: محاسبه فاکتوریل
Part 5: Factorial Calculator
"""
def calculate_factorial():
    """
    شرح کامل:
    این برنامه فاکتوریل عدد ورودی را محاسبه می‌کند.
    فاکتوریل n برابر است با: n × (n-1) × (n-2) × ... × 2 × 1
    
    روش کار:
    1. یک عدد از کاربر می‌گیریم
    2. از 1 تا آن عدد را در هم ضرب می‌کنیم
    
    نکات کلیدی:
    - از متغیر تجمعی برای ضرب اعداد استفاده می‌کنیم
    - حلقه از 1 شروع می‌شود تا عدد ورودی
    
    مثال:
    ورودی: 5
    محاسبات: 1 × 2 × 3 × 4 × 5 = 120
    خروجی: 120
    """
    a = int(input("یک عدد وارد کنید: "))  # دریافت عدد از کاربر
    f = 1                                   # متغیر تجمعی برای ضرب
    for i in range(1, a + 1):              # از 1 تا عدد وارد شده
        f = f * i                          # ضرب در متغیر تجمعی
    print(f"فاکتوریل {a} برابر است با: {f}")

"""
بخش ششم: الگوی لوزی
Part 6: Diamond Pattern
"""
def print_diamond():
    """
    شرح کامل:
    این برنامه یک الگوی لوزی با ستاره چاپ می‌کند.
    
    روش کار:
    1. ابتدا اندازه لوزی را از کاربر می‌گیریم
    2. برای هر سطر:
       - فضای خالی مناسب را چاپ می‌کنیم
       - تعداد مناسبی ستاره چاپ می‌کنیم
    
    نکات کلیدی:
    - تعداد فضای خالی در هر سطر کم می‌شود
    - تعداد ستاره‌ها با فرمول 2*i+1 محاسبه می‌شود
    
    فرمول‌ها:
    - فضای خالی در هر سطر: (a-i-1)
    - تعداد ستاره در هر سطر: (2*i+1)
    
    مثال برای ورودی 4:
    
       *
      ***
     *****
    *******
    """
    a = int(input("اندازه لوزی را وارد کنید: "))
    # چاپ نیمه بالای لوزی
    for i in range(a):
        spaces = " " * (a-i-1)           # محاسبه فضای خالی
        stars = "*" * (2*i+1)            # محاسبه تعداد ستاره‌ها
        print(spaces + stars)            # چاپ هر سطر

